"""data.js as a document: one parser, one renderer.

scrape.py used to treat the published data.js as its database and edit it as
text: results were spliced in by brace counting (inject_results), cards were
read back with a regex that depended on field order (_EXIST_FIGHT_PAT), and
whole vars were swapped with `var NAME=.*?;`, which stops at the first
semicolon inside a value. Every one of those was a way for a stray character to
corrupt the file or for a field to be read wrongly without anyone noticing.

Now a run reads data.js ONCE, here, into plain values (loads), every step edits
those values, and the file is written ONCE from them (dumps). Nothing else in
the scraper matches or edits data.js text.

The grammar is exactly what dumps writes, and the same subset the edge
functions' parseDataJs (supabase/functions/_shared/datajs.js) accepts:

    file   := comment* ( "var" NAME "=" value ";" )*
    value  := object | array | string | number | true | false | null
    object := "{" ( key ":" value ( "," key ":" value )* )? "}"
    key    := identifier | string
    string := a JSON string

Anything else is a DataError, never a guess. dumps(loads(text)) reproduces a
file this module wrote byte for byte (tests/test_datafile.py holds that on the
frozen fixtures), so every other reader of data.js sees the file it always did.

EVENTS is held in the shape scrape.py builds cards in (label / name / record /
ranking); to_json() gives the whole file in the shape the app reads (lbl / n /
r / rk), which is what parseDataJs returns for the same file.
"""

import json
import re

HEADER = "// UFC Dashboard data — generated by scrape.py. Do not edit by hand.\n"

# Written with sorted keys, as the scraper always has.
_SORTED_VARS = {"RESULTS_ARCHIVE", "FIGHTER_ALIASES", "FIGHTER_ESPN"}

_EVENT_KEYS = ("name", "date", "venue", "loc", "slug", "tv", "time",
               "prelimTime", "earlyPrelimTime", "fights")
_FIGHT_KEYS = ("lbl", "wc", "title", "rematch", "odds", "winner", "method",
               "round", "state", "f1", "f2")
_SIDE_KEYS = ("n", "r", "rk", "s")


class DataError(ValueError):
    """data.js is not in the form this module writes."""


# ---------------------------------------------------------------------------
# Parsing
# ---------------------------------------------------------------------------

_TOKEN = re.compile(r"""
    (?P<ws>\s+)
  | (?P<comment>//[^\n]*)
  | (?P<str>"(?:[^"\\\x00-\x1f]|\\.)*")
  | (?P<num>-?(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][+-]?\d+)?)
  | (?P<id>[A-Za-z_$][A-Za-z0-9_$]*)
  | (?P<punct>[{}\[\],:;=])
""", re.VERBOSE)

_MAX_DEPTH = 64


def _tokens(text):
    """(kind, text, offset) for everything but whitespace; comments included."""
    out, pos, n = [], 0, len(text)
    while pos < n:
        m = _TOKEN.match(text, pos)
        if not m:
            raise DataError(f"unexpected character {text[pos]!r} at {pos}")
        kind = m.lastgroup
        if kind != "ws":
            out.append((kind, m.group(), pos))
        pos = m.end()
    out.append(("end", "", n))
    return out


class _Parser:
    def __init__(self, text):
        self.toks = _tokens(text)
        self.i = 0

    def fail(self, what):
        _, tok, pos = self.toks[self.i]
        raise DataError(f"{what} at {pos} (found {tok[:20]!r})")

    def take(self, kind, text=None):
        k, t, _ = self.toks[self.i]
        if k != kind or (text is not None and t != text):
            self.fail(f"{text or kind} expected")
        self.i += 1
        return t

    def at(self, kind, text=None):
        k, t, _ = self.toks[self.i]
        return k == kind and (text is None or t == text)

    def string(self):
        tok = self.take("str")
        try:
            return json.loads(tok)
        except ValueError:
            self.i -= 1
            self.fail("bad string")

    def value(self, depth=0):
        if depth > _MAX_DEPTH:
            self.fail("nesting too deep")
        k, t, _ = self.toks[self.i]
        if k == "str":
            return self.string()
        if k == "num":
            self.i += 1
            return float(t) if any(c in t for c in ".eE") else int(t)
        if k == "id":
            if t not in ("true", "false", "null"):
                self.fail("value expected")
            self.i += 1
            return {"true": True, "false": False, "null": None}[t]
        if k == "punct" and t == "[":
            self.i += 1
            out = []
            if self.at("punct", "]"):
                self.i += 1
                return out
            while True:
                out.append(self.value(depth + 1))
                if self.at("punct", ","):
                    self.i += 1
                    continue
                self.take("punct", "]")
                return out
        if k == "punct" and t == "{":
            self.i += 1
            out = {}
            if self.at("punct", "}"):
                self.i += 1
                return out
            while True:
                key = self.string() if self.at("str") else self.take("id")
                if key in out:
                    self.i -= 1
                    self.fail(f"duplicate key {key!r}")
                self.take("punct", ":")
                out[key] = self.value(depth + 1)
                if self.at("punct", ","):
                    self.i += 1
                    continue
                self.take("punct", "}")
                return out
        self.fail("value expected")

    def file(self):
        while self.at("comment"):
            self.i += 1
        out = {}
        while not self.at("end"):
            self.take("id", "var")
            name = self.take("id")
            if name in out:
                self.i -= 1
                self.fail(f"var {name} declared twice")
            self.take("punct", "=")
            out[name] = self.value()
            self.take("punct", ";")
        return out


def _only(obj, keys, what):
    if not isinstance(obj, dict):
        raise DataError(f"{what} is not an object")
    extra = [k for k in obj if k not in keys]
    if extra:
        raise DataError(f"{what} has a field this scraper does not write: {extra[0]}")
    return obj


def _side_from_js(s, what):
    _only(s, _SIDE_KEYS, what)
    if not isinstance(s.get("n"), str):
        raise DataError(f"{what} has no name")
    return {"name": s["n"], "record": s.get("r", ""), "ranking": s.get("rk", "")}


def _fight_from_js(f, what):
    _only(f, _FIGHT_KEYS, what)
    odds = f.get("odds")
    if odds is not None:
        _only(odds, ("f1", "f2"), what + " odds")
        if set(odds) != {"f1", "f2"} or not all(_is_num(v) for v in odds.values()):
            raise DataError(f"{what} odds are not two numbers")
        odds = {"f1": odds["f1"], "f2": odds["f2"]}
    rnd = f.get("round")
    if rnd is not None and not (isinstance(rnd, int) and not isinstance(rnd, bool)):
        raise DataError(f"{what} round is not a whole number")
    for k in ("lbl", "wc", "winner", "method", "state"):
        if k in f and f[k] is not None and not isinstance(f[k], str):
            raise DataError(f"{what} {k} is not text")
    return {
        # An old file may carry lbl/wc as null; the scraper has always read
        # those back as "" and "TBD".
        "label":   f.get("lbl") or "",
        "wc":      f.get("wc") or "TBD",
        "title":   f.get("title") is True,
        "rematch": f.get("rematch") is True,
        "odds":    odds,
        "winner":  f.get("winner") or "",
        "method":  f.get("method") or "",
        "round":   rnd or None,
        "state":   f.get("state") or "pre",
        "f1":      _side_from_js(f.get("f1"), what + " f1"),
        "f2":      _side_from_js(f.get("f2"), what + " f2"),
    }


def _is_num(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _event_from_js(e, i):
    what = f"EVENTS[{i}]"
    _only(e, _EVENT_KEYS, what)
    for k in ("name", "date"):
        if not isinstance(e.get(k), str) or not e[k]:
            raise DataError(f"{what} has no {k}")
    for k in _EVENT_KEYS[2:-1]:
        if k in e and not isinstance(e[k], str):
            raise DataError(f"{what} {k} is not text")
    fights = e.get("fights")
    if not isinstance(fights, list):
        raise DataError(f"{what} has no fights list")
    out = {k: e[k] for k in _EVENT_KEYS[:-1] if k in e}
    out["fights"] = [_fight_from_js(f, f"{what} fight {j}") for j, f in enumerate(fights)]
    return out


def loads(text):
    """data.js text -> {var name: value}, in file order.

    EVENTS comes back in the scraper's own card shape (see the module
    docstring); every other var is the plain value. Raises DataError on
    anything dumps would not have written.
    """
    doc = _Parser(text).file()
    if "EVENTS" in doc:
        if not isinstance(doc["EVENTS"], list):
            raise DataError("EVENTS is not a list")
        doc["EVENTS"] = [_event_from_js(e, i) for i, e in enumerate(doc["EVENTS"])]
    return doc


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------

def fight_js(f, comma=""):
    """Serialise a single fight dict to a JS object literal string."""
    f1   = f["f1"]
    f2   = f["f2"]
    odds = f.get("odds")
    odds_s = f"{{f1:{odds['f1']},f2:{odds['f2']}}}" if odds else "null"
    rnd    = str(f.get("round") or "null")
    return (
        f"      {{lbl:{json.dumps(f.get('label', ''))},wc:{json.dumps(f.get('wc', 'TBD'))},"
        f"title:{'true' if f.get('title') else 'false'},"
        f"rematch:{'true' if f.get('rematch') else 'false'},odds:{odds_s},"
        f"winner:{json.dumps(f.get('winner', ''))},method:{json.dumps(f.get('method', ''))},"
        f"round:{rnd},state:{json.dumps(f.get('state', 'pre'))},"
        f"f1:{{n:{json.dumps(f1.get('name', 'TBD'))},r:{json.dumps(f1.get('record', ''))},"
        f"rk:{json.dumps(f1.get('ranking', ''))},s:null}},"
        f"f2:{{n:{json.dumps(f2.get('name', 'TBD'))},r:{json.dumps(f2.get('record', ''))},"
        f"rk:{json.dumps(f2.get('ranking', ''))},s:null}}}}{comma}"
    )


def events_js(evs):
    """Serialise the events list to a JS array literal (value only, no var declaration)."""
    lines = ["["]
    for ei, ev in enumerate(evs):
        c = "," if ei < len(evs) - 1 else ""
        lines += [
            "  {",
            f"    name:{json.dumps(ev['name'])},",
            f"    date:{json.dumps(ev['date'])},",
            f"    venue:{json.dumps(ev.get('venue', ''))},",
            f"    loc:{json.dumps(ev.get('loc', ''))},",
        ]
        # The article slug is persisted so later runs never have to rebuild it
        # from the ASCII-folded name (which loses diacritics — Medić → Medic —
        # and then points at a title that doesn't exist).
        if ev.get("slug"):
            lines.append(f"    slug:{json.dumps(ev['slug'])},")
        lines += [
            f"    tv:{json.dumps(ev.get('tv', 'Paramount+'))},",
            f"    time:{json.dumps(ev.get('time', 'TBD'))},",
        ]
        if ev.get("prelimTime"):
            lines.append(f"    prelimTime:{json.dumps(ev['prelimTime'])},")
        # Field order is load-bearing for readers that still match this text
        # (health.py, write_status.py, kick-scraper, send-push): add new fields
        # after the ones they anchor on, never between them.
        if ev.get("earlyPrelimTime"):
            lines.append(f"    earlyPrelimTime:{json.dumps(ev['earlyPrelimTime'])},")
        lines.append("    fights:[")
        fights = ev.get("fights", [])
        for fi, fight in enumerate(fights):
            lines.append(fight_js(fight, "," if fi < len(fights) - 1 else ""))
        lines += ["    ]", f"  }}{c}"]
    lines.append("]")
    return "\n".join(lines)


def _var_js(name, value):
    if name == "EVENTS":
        return events_js(value)
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False,
                      sort_keys=name in _SORTED_VARS, allow_nan=False)


def dumps(doc):
    """{var name: value} -> data.js text. EVENTS is written last, as always:
    a var added since the file was read lands ahead of it."""
    names = [n for n in doc if n != "EVENTS"] + (["EVENTS"] if "EVENTS" in doc else [])
    return HEADER + "".join(f"var {n}={_var_js(n, doc[n])};\n" for n in names)


def checked_dumps(doc):
    """dumps, refusing a document that would not read back as itself.

    The last line of defence before the file is written: a value the renderer
    cannot express faithfully (a NaN, an odds line that is not a number, a key
    that is not a string) raises here instead of reaching the published file.
    """
    try:
        text = dumps(doc)
        back = loads(text)
    except DataError:
        raise
    except (TypeError, ValueError, KeyError, AttributeError) as e:
        raise DataError(f"document cannot be written: {e}") from e
    if to_json(back) != to_json(doc):
        raise DataError("document does not read back as written")
    return text


# ---------------------------------------------------------------------------
# The JSON view (what the app, and parseDataJs, see)
# ---------------------------------------------------------------------------

def _side_to_js(s):
    return {"n": s.get("name", "TBD"), "r": s.get("record", ""),
            "rk": s.get("ranking", ""), "s": None}


def _fight_to_js(f):
    odds = f.get("odds")
    return {
        "lbl": f.get("label", ""), "wc": f.get("wc", "TBD"),
        "title": bool(f.get("title")), "rematch": bool(f.get("rematch")),
        "odds": {"f1": odds["f1"], "f2": odds["f2"]} if odds else None,
        "winner": f.get("winner", ""), "method": f.get("method", ""),
        "round": f.get("round") or None, "state": f.get("state", "pre"),
        "f1": _side_to_js(f["f1"]), "f2": _side_to_js(f["f2"]),
    }


def _event_to_js(ev):
    out = {"name": ev["name"], "date": ev["date"],
           "venue": ev.get("venue", ""), "loc": ev.get("loc", "")}
    if ev.get("slug"):
        out["slug"] = ev["slug"]
    out["tv"] = ev.get("tv", "Paramount+")
    out["time"] = ev.get("time", "TBD")
    for k in ("prelimTime", "earlyPrelimTime"):
        if ev.get(k):
            out[k] = ev[k]
    out["fights"] = [_fight_to_js(f) for f in ev.get("fights", [])]
    return out


def to_json(doc):
    """The document as the app reads it: what evaluating data.js yields."""
    return {n: ([_event_to_js(e) for e in v] if n == "EVENTS" else v)
            for n, v in doc.items()}


if __name__ == "__main__":
    import sys
    path = sys.argv[1] if len(sys.argv) > 1 else "data.js"
    with open(path, encoding="utf-8") as fh:
        json.dump(to_json(loads(fh.read())), sys.stdout, ensure_ascii=False,
                  separators=(",", ":"))
